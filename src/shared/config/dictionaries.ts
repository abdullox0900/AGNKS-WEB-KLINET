export type Locale = keyof typeof dictionaries
export type DictKey = keyof (typeof dictionaries)['uz']

/** Replaces every `{var}` placeholder. Usable outside React (e.g. class components). */
export function translate(locale: Locale, key: DictKey, vars?: Record<string, string | number>): string {
  let str: string = (dictionaries[locale] as Record<string, string>)[key] ?? dictionaries.uz[key] ?? key
  if (vars) {
    for (const [k, v] of Object.entries(vars)) str = str.split(`{${k}}`).join(String(v))
  }
  return str
}
